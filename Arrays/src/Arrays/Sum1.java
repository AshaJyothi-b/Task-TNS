package Arrays;

public class Sum1 {

	public static void main(String[] args) {
		        int[] arr = {2, 4, 6, 8, 10};
		        int sum = 0;

		        for(int i = 0; i < 5; i++) {
		            sum = sum + arr[i];
		        }

		        System.out.println("Sum of all elements = " + sum);
		    
		

	}

}
